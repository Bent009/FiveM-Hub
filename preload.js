const { contextBridge, ipcRenderer } = require("electron");

contextBridge.exposeInMainWorld("fivemAPI", {
    launch: () => ipcRenderer.invoke("launch-fivem"),
    getCpuInfo: () => ipcRenderer.invoke("get-cpu-info"),
    savePriority: (priority) => ipcRenderer.invoke("save-priority", priority),
    saveAffinity: (affinity) => ipcRenderer.invoke("save-affinity", affinity),
    getPriority: () => ipcRenderer.invoke("get-priority"),
    getAffinity: () => ipcRenderer.invoke("get-affinity"),
    getServers: () => ipcRenderer.invoke("get-servers"),
    fetchCfxMetadata: (rawInput) => ipcRenderer.invoke("fetch-cfx-metadata", rawInput),
    saveServer: (serverPayload) => ipcRenderer.invoke("save-server", serverPayload),
    deleteServer: (serverId) => ipcRenderer.invoke("delete-server", serverId),
    launchServer: (serverId) => ipcRenderer.invoke("launch-server", serverId),
    connectNow: () => ipcRenderer.invoke("connect-now"),
    cancelLaunch: () => ipcRenderer.invoke("cancel-launch"),
    onLaunchProgress: (callback) => {
        const listener = (_event, payload) => callback(payload);
        ipcRenderer.on("launch-progress", listener);
        return () => ipcRenderer.removeListener("launch-progress", listener);
    },
    browseFiveM: () => ipcRenderer.invoke("browse-fivem"),
    toggleFavorite: (serverId) => ipcRenderer.invoke("toggle-favorite", serverId),
    getFavorites: () => ipcRenderer.invoke("get-favorites"),
    saveLaunchDelay: (delay) => ipcRenderer.invoke("save-launch-delay", delay),
    getLaunchDelay: () => ipcRenderer.invoke("get-launch-delay"),
    createProfile: (profileName) => ipcRenderer.invoke("create-profile", profileName),
    saveCache: (profileName) => ipcRenderer.invoke("save-cache", profileName),
    loadCache: (profileName) => ipcRenderer.invoke("load-cache", profileName),
    getProfiles: () => ipcRenderer.invoke("get-profiles"),
    getProfilesDetailed: () => ipcRenderer.invoke("get-profiles-detailed"),
    deleteProfile: (profileName) => ipcRenderer.invoke("delete-profile", profileName),
    getCacheMode: () => ipcRenderer.invoke("get-cache-mode"),
    saveCacheMode: (mode) => ipcRenderer.invoke("save-cache-mode", mode),
    getModProfiles: () => ipcRenderer.invoke("get-mod-profiles"),
    switchModProfile: (targetProfileName) => ipcRenderer.invoke("switch-mod-profile", targetProfileName),
    saveModDescription: (profileName, description) => ipcRenderer.invoke("save-mod-description", profileName, description),
    createModProfile: (profileName) => ipcRenderer.invoke("create-mod-profile", profileName),
    openModFolder: (folderName) => ipcRenderer.invoke("open-mod-folder", folderName),
    getFiveMPath: () => ipcRenderer.invoke("get-fivem-path"),
    exportConfig: () => ipcRenderer.invoke("export-config"),
    importConfig: () => ipcRenderer.invoke("import-config"),
    getServerStatus: (endpoint) => ipcRenderer.invoke("get-server-status", endpoint),
    getTheme: () => ipcRenderer.invoke("get-theme"),
    saveTheme: (theme) => ipcRenderer.invoke("save-theme", theme),
    getAccountTier: () => ipcRenderer.invoke("get-account-tier"),
    activateAccountTier: (token) => ipcRenderer.invoke("activate-account-tier", token),
    activateLicense: (token) => ipcRenderer.invoke("activate-account-tier", token),
    isFiveMRunning: () => ipcRenderer.invoke("check-fivem-running"),
    getCleanupStats: () => ipcRenderer.invoke("get-cleanup-stats"),
    performCleanup: () => ipcRenderer.invoke("perform-cleanup"),
    minimizeWindow: () => ipcRenderer.invoke("window-minimize"),
    maximizeWindow: () => ipcRenderer.invoke("window-maximize"),
    closeWindow: () => ipcRenderer.invoke("window-close")
});